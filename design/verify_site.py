"""Check actual generated page/resource paths. This does not render a browser."""
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit, unquote
import json,re

SITE=Path(__file__).resolve().parent.parent

class Page(HTMLParser):
    def __init__(self,text):
        super().__init__();self.refs=[];self.ids=[];self.mains=0;self.errors=[];self.redirect=False;self.feed(text)
    def handle_starttag(self,tag,attrs):
        a=dict(attrs)
        if 'id' in a:self.ids.append(a['id'])
        if tag=='main':self.mains+=1
        if tag=='meta' and a.get('http-equiv','').lower()=='refresh':
            self.redirect=True
            match=re.search(r'url=(.+)',a.get('content',''),re.I)
            if match:self.refs.append((tag,'content',match[1].strip(' \"\'')))
        if tag=='img' and 'alt' not in a:self.errors.append('Image has no alt attribute')
        for key in ('href','src'):
            if a.get(key):self.refs.append((tag,key,a[key]))

def verify():
    catalog=json.loads((SITE/'design/catalog.json').read_text(encoding='utf-8'))['templates']
    # Include aliases, redirects and the Vite source entry, not only catalog targets.
    pages=sorted(p.relative_to(SITE).as_posix() for p in SITE.rglob('*.html') if not any(part in {'.git','node_modules','__pycache__'} for part in p.relative_to(SITE).parts))
    parsed={name:Page((SITE/name).read_text(encoding='utf-8-sig')) for name in pages}
    checked=set();errors=[];refs=0
    # These exact IDs are generated by Meros from its known catalog in app.js.
    from build_collection import DATA
    dynamic={'design/meros-site/index.html':{'work-'+item['id'] for item in DATA['meros']}}
    def resolve(owner,value):
        nonlocal refs
        parts=urlsplit(value)
        if parts.scheme or parts.netloc:return
        path=unquote(parts.path)
        if path.startswith('/ustoz/'):return # Separate research repository.
        target=(owner if not path else SITE/path.lstrip('/') if path.startswith('/') else owner.parent/path).resolve()
        if owner==SITE/'design/material-expressive/index.html' and path:
            # Vite's development entry resolves /src and public/ through its dev server.
            base=owner.parent
            target=base/path.lstrip('/')
            if not target.exists():target=base/'public'/path.lstrip('./')
        if not target.is_relative_to(SITE):errors.append(f'{owner}: path escapes site: {value}');return
        if target.is_dir():target=target/'index.html'
        refs+=1
        if not target.is_file():errors.append(f'{owner.relative_to(SITE)}: missing {value}');return
        target_name=target.relative_to(SITE).as_posix()
        if parts.fragment and target_name in parsed:
            if unquote(parts.fragment) not in set(parsed[target_name].ids)|dynamic.get(target_name,set()):
                errors.append(f'{owner.relative_to(SITE)}: missing target anchor {value}')
        if target.suffix.lower() in ('.css','.js','.mjs'):resource(target)
    def resource(path):
        if path in checked:return
        checked.add(path);text=path.read_text(encoding='utf-8-sig')
        if path.suffix=='.css':
            for value in re.findall(r'url\(\s*[\'"]?([^\s\'"\)]+)',text):resolve(path,value)
        else:
            for value in re.findall(r'(?:from\s*|import\s*)[\'"](\.{1,2}/[^\'"]+)',text):resolve(path,value)
    for name in pages:
        path=SITE/name;page=parsed[name]
        if len(page.ids)!=len(set(page.ids)):errors.append(name+': duplicate IDs')
        if name not in ('design/material-expressive/dist/index.html','design/material-expressive/index.html') and not page.redirect and page.mains!=1:errors.append(name+': expected one main')
        errors.extend(name+': '+error for error in page.errors)
        for tag,key,value in page.refs:
            resolve(path,value)
            if value.startswith('#') and len(value)>1 and unquote(value[1:]) not in set(page.ids)|dynamic.get(name,set()):errors.append(name+': missing anchor '+value)
    result={'pages':len(pages),'local_references':refs,'scripts_and_styles':len(checked),'errors':errors,'scope':'Static generated HTML/resources; no browser rendering or remote-link assertions.'}
    print(json.dumps(result,ensure_ascii=False,indent=2));assert not errors
    return result

if __name__=='__main__':verify()
